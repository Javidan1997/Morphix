import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import puppeteer from 'puppeteer-core';
const base = process.env.BASE || 'http://localhost:4173';
const browser = await puppeteer.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const results=[];
const wait = (ms) => new Promise(resolve=>setTimeout(resolve,ms));
try {
 for (const slug of ['forma','edito']) {
  const page=await browser.newPage();
  await page.setViewport({width:1440,height:900});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{if(response.status()>=400 && response.url().startsWith(base))errors.push(response.status()+' '+response.url());});
  await page.goto(`${base}/shopify-templates/${slug}`,{waitUntil:'domcontentloaded'});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
  assert.equal(await page.$eval('h1',el=>el.textContent),slug==='forma'?'A slower way to live.':'Wear your own point of view.');
  await page.screenshot({path:`docs/templates/screenshots/${slug}-desktop-1440.jpg`});
  await page.evaluate(()=>{const el=document.querySelector('[data-motion-hero]');scrollTo(0,el.getBoundingClientRect().top+scrollY+(el.offsetHeight-innerHeight)*.6);});
  await wait(500);
  await page.waitForFunction(()=>document.querySelector('video').currentTime>1);
  const time=await page.$eval('video',el=>el.currentTime);
  assert(time>1,'Video advances with scroll');
  await page.evaluate(()=>document.querySelector('#approach').scrollIntoView());await wait(1100);
  await page.screenshot({path:`docs/templates/screenshots/${slug}-editorial-1440.jpg`});
  await page.evaluate(()=>{const el=document.querySelector('[data-motion-scene]');scrollTo(0,el.getBoundingClientRect().top+scrollY+(el.offsetHeight-innerHeight)*.5);});await wait(300);
  const slide=await page.$eval('[data-scene-panel]:nth-child(2)',el=>parseFloat(el.style.getPropertyValue('--slide')));
  assert(slide>20&&slide<80,'Story chapter slides horizontally');
  await page.screenshot({path:`docs/templates/screenshots/${slug}-scene-1440.jpg`});
  await page.evaluate(()=>document.querySelector('#collection').scrollIntoView());await wait(700);
  if(slug==='edito'){
   const start=await page.$eval('.motion-collection',el=>el.style.getPropertyValue('--collection-shift'));
   await page.evaluate(()=>{const el=document.querySelector('#collection');scrollTo(0,el.getBoundingClientRect().top+scrollY+(el.offsetHeight-innerHeight)*.8);});await wait(400);
   const end=await page.$eval('.motion-collection',el=>el.style.getPropertyValue('--collection-shift'));
   assert.notEqual(start,end,'Fashion collection moves horizontally');
   await page.evaluate(()=>document.querySelector('#collection').scrollIntoView());await wait(1100);
   await page.select('.motion-product select',''+await page.$eval('.motion-product select',el=>el.options[2].value));
  }
  await page.screenshot({path:`docs/templates/screenshots/${slug}-collection-1440.jpg`});
  await page.click('.motion-product button[type=submit]');
  await page.waitForSelector('cfg-cart-drawer dialog[open]');
  assert((await page.$eval('[data-cart-lines]',el=>el.textContent)).includes(slug==='forma'?'Arc lounge chair':'The tailored jacket'));
  if(slug==='edito')assert((await page.$eval('[data-cart-lines]',el=>el.textContent)).includes('M'));
  await page.keyboard.press('Escape');
  await page.evaluate(()=>scrollTo(0,0));await wait(200);
  await page.click('[data-motion-toggle]');
  assert.equal(await page.$eval('[data-motion-toggle]',el=>el.getAttribute('aria-pressed')),'true');
  assert.equal(await page.$eval('[data-motion-scene]',el=>getComputedStyle(el).height),await page.$eval('.motion-scene__stage',el=>getComputedStyle(el).height));
  await page.screenshot({path:`docs/templates/screenshots/${slug}-static-full.jpg`,fullPage:true});
  await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
  await page.reload({waitUntil:'domcontentloaded'});
  assert.equal(await page.$eval('[data-motion-toggle]',el=>el.hidden),true);
  assert.equal(await page.$eval('video',el=>Boolean(el.dataset.loaded)),false);
  await page.setViewport({width:390,height:844,isMobile:true,hasTouch:true});
  await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'no-preference'}]);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>{const image=document.querySelector('.motion-hero img');return image.complete && image.naturalWidth>0;});
  await page.evaluate(()=>document.fonts.ready);
  await wait(400);
  await page.screenshot({path:`docs/templates/screenshots/${slug}-mobile-390.jpg`});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false,'No unintended mobile horizontal overflow');
  await page.evaluate(()=>document.querySelector('#collection').scrollIntoView());await wait(1100);
  await page.screenshot({path:`docs/templates/screenshots/${slug}-collection-mobile.jpg`});
  assert.equal(await page.$$('.motion-product').then(a=>a.length),3);
  await page.click('.motion-product button[type=submit]');await page.waitForSelector('cfg-cart-drawer dialog[open]');
  assert.deepEqual(errors,[],'No asset or runtime errors');
  results.push({slug,videoTime:time,slide,desktop:'1440x900',mobile:'390x844',cart:'passed',reducedMotion:'passed',errors});
  await page.close();
 }
 const gallery=await browser.newPage();await gallery.goto(`${base}/shopify-templates/`,{waitUntil:'domcontentloaded'});
 assert.equal(await gallery.$$('.tpl-card').then(a=>a.length),7);
 await gallery.evaluate(()=>[...document.querySelectorAll('.work-filter button')].find(el=>el.textContent==='Fashion').click());
 assert.equal(await gallery.$$('.tpl-card').then(a=>a.length),1);
 assert((await gallery.$eval('.tpl-card',el=>el.textContent)).includes('Édito'));
 await gallery.close();
 console.log(JSON.stringify(results,null,2));
 mkdirSync('docs/templates',{recursive:true});
 writeFileSync('docs/templates/motion-checks.json',JSON.stringify(results,null,2)+'\n');
} finally { await browser.close(); }
