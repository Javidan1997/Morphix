// Regressions for native Shopify behavior beyond the small public fixtures.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createShopifyEngine } from './liquid-engine.mjs';
import { luxuryFixture } from '../../shopify/demo/luxury.mjs';
import { shop } from '../../shopify/demo/shop.mjs';
const themeDir = resolve('shopify/theme');
const fixture = luxuryFixture('edito', 'products/tailored-jacket');
const source = fixture.context.product;
const locale = JSON.parse(readFileSync(resolve(themeDir, 'locales/en.default.json'), 'utf8'));
const renderer = createShopifyEngine({themeDir, assetBase:'/assets/', locale, data:{shop, all_products:fixture.products, collections:fixture.collections}});
const base = {shop, settings:{brand:'edito', demo_mode:false}, template:{name:'product',suffix:'edito'}};
source.selected_or_first_available_variant = source.variants[2];
source.variants[2].price = 37500;
const productHtml = await renderer.renderSection('main',{type:'cfg-lux-product'},{...base,product:source});
assert.match(productHtml, new RegExp(`<option value="${source.variants[2].id}"[^>]* selected[^>]*>M</option>`));
assert.match(productHtml, /data-lx-price>\$375</);
const products = Array.from({length:70},(_,i)=>({...source,handle:`piece-${i+1}`,title:`Catalog piece ${i+1}`,url:`/products/piece-${i+1}`,type:'Tailoring'}));
const collection = {title:'Full collection',url:'/collections/all',products,products_count:70,sort_by:'price-ascending',sort_options:[{value:'manual',name:'Featured'},{value:'price-ascending',name:'Price: low to high'}],filters:[{param_name:'filter.p.product_type',values:[{label:'Tailoring',active:false,url_to_add:'?filter.p.product_type=Tailoring'}]}]};
const collectionHtml = await renderer.renderSection('main',{type:'cfg-lux-collection'},{...base,template:{name:'collection',suffix:'edito'},collection,current_page:3});
assert.equal((collectionHtml.match(/class="lx-card"/g)||[]).length,22);
assert.match(collectionHtml, /Catalog piece 70/);
assert.doesNotMatch(collectionHtml, />Catalog piece 1</);
assert.match(collectionHtml, /href="\?page=2"/);
assert.match(collectionHtml, /aria-current="page">3/);
assert.match(collectionHtml, /data-lx-live-sort/);
assert.match(collectionHtml, /value="price-ascending" selected/);
assert.match(collectionHtml, /href="\?filter.p.product_type=Tailoring"/);
assert.doesNotMatch(collectionHtml, /data-lx-filter=/);
const articles = Array.from({length:31},(_,i)=>({...fixture.context.blogs.journal.articles[0],title:`Journal story ${i+1}`,url:`/blogs/journal/story-${i+1}`}));
const blog = {articles};
const journalHtml = await renderer.renderSection('main',{type:'cfg-lux-journal'},{...base,template:{name:'blog',suffix:'edito'},blog,current_page:3});
assert.equal((journalHtml.match(/<article data-lx-reveal>/g)||[]).length,7);
assert.match(journalHtml, /Journal story 31/);
assert.doesNotMatch(journalHtml, />Journal story 1</);
assert.match(journalHtml, /href="\?page=2"/);
const previewHtml = await renderer.renderSection('main',{type:'cfg-lux-journal'},{...base,template:{name:'index',suffix:'edito'},blog});
assert.equal((previewHtml.match(/<article data-lx-reveal>/g)||[]).length,2);
console.log('Luxury Liquid regressions passed: linked variant, 70-product catalog, native filters/sort, 31-article journal, two-story home preview.');
